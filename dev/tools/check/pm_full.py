"""pm-full: one gate (C-2b or isomer-screen shape) on ONE Perlmutter GPU node (4 x A100). BILLED: dry run only here.

  python -m tools.check pm-full --shape c2b|isomer [--test-only] [--no-mps] [--no-pack-arms]   # build + estimate
  python -m tools.check pm-full --shape c2b --qos NAME --approved                         # refused in this package

The job: one `tools.run panel` per GPU (CUDA_VISIBLE_DEVICES=i, adaptive lanes up to 4), parents sharded over the four
GPUs by recorded cost (longest first, greedy), every arm and seed of a parent in the same work item on the same GPU,
so all arms of the comparison run on the same node type and the pairing rule holds. Outputs are packed per GPU
(`--pack`: one run_pack tar per runner, inode quota). Preflight refuses without 4 GPUs, a working xtb, the expected
fingerprint and the MACE model hash. Data comes from $JK_SCR/data (staged; MANIFEST.sha256 there).

Node-hour estimate: recorded per-parent seconds (dev/tools/run/costs.json, local 2060) x the measured A100/2060 factor
(login-node A100, same parents: bench 216 s vs 268 s recorded = 0.81; isomer 98.7 s vs 87 s = 1.13) / (4 GPUs x
lane gain: 4 lanes with MPS 2.25, without 1.83, login A100, same 12 parents), floored by the longest work item, + setup.
Every billed job needs the owner's go with the QOS named; this package never submits.
"""
from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

from .common import REPO, Report, stamp

A100_FACTOR = dict(bench=0.81, isomer=1.13)   # login A100 parent wall / 2060 recorded, same parents (bench: 12
                                              # parents, 216 s at 1 lane, 2026-11-08 12:29; isomer: 98.7 s vs 87 s)
#: per-GPU throughput of 4 lanes over 1 lane on the login A100, same 12 parents (2026-11-08): sum of 1-lane parent walls
#: 216 s / 4-lane wall: 118 s without MPS, 96 s with MPS. A lower bound: those 4-lane walls are set by the longest
#: parents (XUKKIA 62 s), so a 30-parent shard per GPU gains more. 8 lanes: 113 / 98 s (no better; 21 GB RSS).
LANE_GAIN = dict(off=1.83, mps=2.25)
SETUP_S = 180.0                               # preflight + lane start (imports, MACE, DB, GFN2 self-check: first
                                              # parent started 9.3 s after launch on the login A100) + pack, with margin
#: the C-2b arm cost relative to C: K, P re-seed and solve the same rows; S1 (single_w48) is a full prepare and a
#: width-48 solve per seed (about one C-arm cost in the C-2b confirmation records)
SHAPES = {
    "c2b": dict(backend="bench", arms="C,K,P,S1", seeds="21,22,23", arm_cost=4.0),
    "isomer": dict(backend="isomer", arms="C,A,AS,ASP", seeds="11,12,13", arm_cost=None),
}
EXPECTED_FP = "2c87e2940af2"

SCRIPT = r"""#!/bin/bash
#SBATCH -A m5184_g
#SBATCH -C gpu
#SBATCH -q {qos}
#SBATCH -N 1
#SBATCH --ntasks=1
#SBATCH -c 128
#SBATCH --gpus=4
#SBATCH -t {minutes}
#SBATCH -J jk-gate-{shape}
#SBATCH -L scratch
#SBATCH -o {out}/slurm-%j.out
# The -o directory must exist before submission: mkdir -p {out}
# Generated by `python -m tools.check pm-full --shape {shape}` at {stamp}. BILLED: submit only with the owner's go.
set -uo pipefail
source "$HOME/scripts/jacobik/jk_env.sh"
OUT={out}/job_${{SLURM_JOB_ID}}
mkdir -p "$OUT"
cd "$JK_SRC"
export OMP_NUM_THREADS=1 MKL_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1
# --- Discord notices: start, every 5 min (tools.run stats), end with the logs attached. notify.py (dev/tools/run/notify.py) is
# copied to $HOME/scripts/jacobik; the webhook URL is read from ~/.config/jacobik/discord_webhook (never in git). Silent no-op without it.
NPY="$HOME/scripts/jacobik/notify.py"
NOTIFY() {{ [ -f "$NPY" ] && timeout 90 $JK_PY "$NPY" "$@" || true; }}
T0=$(date +%s); WATCH=
finish() {{
  rc=$?; [ -n "$WATCH" ] && kill $WATCH 2>/dev/null
  NOTIFY file {out}/slurm-${{SLURM_JOB_ID}}.out "$OUT"/g*.log \
    --text "job $SLURM_JOB_ID $([ $rc = 0 ] && echo DONE || echo FAILED) rc=$rc after $(( ($(date +%s)-T0)/60 )) min | $(timeout 60 $JK_PY "$NPY" stats --out "$OUT" 2>/dev/null)"
}}
trap finish EXIT
trap 'echo "SIGTERM (time limit)"; exit 143' TERM
# --- preflight: refuse rather than produce invalid structures
[ "$(nvidia-smi -L | wc -l)" -ge 4 ] || {{ echo "preflight: fewer than 4 GPUs"; exit 3; }}
command -v xtb >/dev/null || [ -n "${{JACOBIK_XTB:-}}" ] || {{ echo "preflight: no xtb"; exit 3; }}
FP=$($JK_PY -c 'from jacobik.core import profile; print(profile.snapshot()["fingerprint"])')
[ "$FP" = "{fp}" ] || {{ echo "preflight: fingerprint $FP != {fp}"; exit 3; }}
echo "{model_sha}  research/bench/tools/jdev/MACE-POLAR-1-S.model" | sha256sum -c --quiet || {{ echo "preflight: MACE model hash"; exit 3; }}
git -C "$JK_SRC" rev-parse HEAD > "$OUT/commit.txt"
nvidia-smi > "$OUT/nvidia-smi.txt"
NOTIFY msg "job $SLURM_JOB_ID STARTED on $(hostname) (QOS {qos}, limit {minutes} min); preflight passed"
[ -f "$NPY" ] && {{ $JK_PY "$NPY" watch --out "$OUT" --every 300 --label "job $SLURM_JOB_ID" > /dev/null 2>&1 & WATCH=$!; }}
# --- one runner per GPU; all arms and seeds of a parent stay on one GPU (pairing rule)
{runners}
wait
echo "gate done $(date)" >> "$OUT/done.txt"
"""

RUNNER = ('CUDA_VISIBLE_DEVICES={g} TOOLS_RUN_GPU_INDEX={g} timeout {tmo} nice -n 5 $JK_PY -m tools.run panel '
          '--out "$OUT/g{g}" --name {shape}_g{g} --backend {backend} {extra}--codes {codes} --arms {arms} --seeds {seeds} '
          '--max-lanes 4 --cpu-cap 30 --max-rss-gb 55 --pack --yes{mps}{pack_arms} > "$OUT/g{g}.log" 2>&1 &')


def shard(costs: dict, n: int = 4) -> list[list[str]]:
    bins = [[0.0, []] for _ in range(n)]
    for code, c in sorted(costs.items(), key=lambda kv: -kv[1]):
        b = min(bins, key=lambda x: x[0])
        b[0] += c
        b[1].append(code)
    return [b[1] for b in bins]


def gate_costs(shape: str) -> dict:
    """Recorded 2060 seconds per whole parent work item (every arm and seed)."""
    t = json.loads((REPO / "dev/tools/run/costs.json").read_text())
    codes = json.loads((REPO / "research/campaigns/c2/C2_PANEL.json").read_text())["codes"]
    sh = SHAPES[shape]
    if sh["backend"] == "bench":
        per = t["bench_c_per_seed_s"]
        med = sorted(per.values())[len(per) // 2]
        return {c: per.get(c, med) * 3 * sh["arm_cost"] for c in codes}
    iso = t["isomer_parent_s"]
    med = sorted(iso.values())[len(iso) // 2]
    return {c: iso.get(c, med) for c in codes}


def estimate(shape: str, pack_arms: bool = True, mps: bool = True) -> dict:
    costs = gate_costs(shape)
    f = A100_FACTOR[SHAPES[shape]["backend"]]
    tot = sum(costs.values()) * f
    # isomer work items are single seeds (split_seeds): the longest item is a third of the parent
    longest = max(costs.values()) * f / (3.0 if SHAPES[shape]["backend"] == "isomer" else 1.0)
    bins = shard(costs)
    gain = LANE_GAIN["mps" if mps else "off"]
    per_gpu = [sum(costs[c] for c in b) * f / gain for b in bins]
    compute = max(max(per_gpu), longest)
    wall = compute + SETUP_S
    out = dict(shape=shape, parents=len(costs), serial_2060_s=round(sum(costs.values())), a100_factor=f,
               lane_gain=gain, mps=mps, per_gpu_s=[round(x) for x in per_gpu], longest_item_s=round(longest),
               wall_s=round(wall), wall_min=round(wall / 60, 1), node_hours=round(wall / 3600, 2),
               note="regular/debug QOS charge factor 1 per node-hour assumed; shared QOS is not a 4-GPU node")
    if shape == "c2b" and pack_arms:
        # arm packing: C, K, P in one solve; on the 2060 AWONOR solve wall 3 x 6.97 s -> 14.9 s at 3x rows
        # (0.71); the solve is about half of a median parent's wall, so about 0.85 x the bench work in total
        out["with_pack_arms_wall_min"] = round((compute * 0.85 + SETUP_S) / 60, 1)
        out["with_pack_arms_node_hours"] = round((compute * 0.85 + SETUP_S) / 3600, 2)
    return out


def build_script(shape: str, out_dir: str, qos: str, minutes: int, mps: bool, pack_arms: bool) -> str:
    sh = SHAPES[shape]
    bins = shard(gate_costs(shape))
    extra = ""
    if sh["backend"] == "isomer":
        extra = ('--repo "$JK_SCR/ext/jgen-i" --isomer-script "$JK_SCR/ext/jgen-i/research/campaigns/i/'
                 'run_i_screen.py" --env RUNKIT_REMOTE=1 ')
    runners = "\n".join(RUNNER.format(g=g, tmo=max(60, (minutes - 5) * 60), shape=shape, backend=sh["backend"], extra=extra,
                                      codes=",".join(b), arms=sh["arms"], seeds=sh["seeds"],
                                      mps=" --mps" if mps else "",
                                      pack_arms=" --pack-arms" if (pack_arms and sh["backend"] == "bench") else "")
                        for g, b in enumerate(bins))
    model = REPO / "research/bench/tools/jdev/MACE-POLAR-1-S.model"
    model_sha = "e4495612" if not model.exists() else __import__("hashlib").sha256(model.read_bytes()).hexdigest()
    return SCRIPT.format(qos=qos, minutes=minutes, shape=shape, out=out_dir, stamp=stamp(), fp=EXPECTED_FP,
                         model_sha=model_sha, runners=runners)


def run(args) -> int:
    shape = getattr(args, "shape", None) or "c2b"
    out = Path(args.out_dir) if args.out_dir else REPO / "research/data/infra/fastcheck/pm-full"
    rep = Report(f"pm-full-{shape}", out)
    pack_arms = not getattr(args, "no_pack_arms", False)
    mps = not getattr(args, "no_mps", False)
    est = estimate(shape, pack_arms, mps)
    minutes = int(est["wall_min"] * 1.5) + 10           # ceiling only; billing is on time used
    remote_out = f"{getattr(args, 'remote_out', None) or '/pscratch/sd/a/achen310/jacobik/runs'}/gate_{shape}"
    script = out / f"pm_full_{shape}_{stamp()}.sbatch"
    out.mkdir(parents=True, exist_ok=True)
    script.write_text(build_script(shape, remote_out,
                                   getattr(args, "qos", None) or "REQUIRED_QOS", minutes,
                                   mps, pack_arms))
    print(f"[pm-full] {shape}: estimate {json.dumps(est)}")
    print(f"[pm-full] script: {script} (time limit {minutes} min)")
    if not (getattr(args, "qos", None) and getattr(args, "approved", False)):
        rep.run("dry run", lambda: (True, "no submission: --qos NAME --approved not both given",
                                    dict(estimate=est, script=str(script))))
        if shutil.which("sbatch") and getattr(args, "test_only", False):
            rep.run("sbatch --test-only", lambda: _test_only(script))
        return rep.finish()
    raise SystemExit("pm-full submission is not part of infra/fastcheck; the owner submits billed jobs")


def _test_only(script: Path):
    r = subprocess.run(["sbatch", "--test-only", str(script)], capture_output=True, text=True, timeout=120)
    msg = (r.stdout + r.stderr).strip().splitlines()
    return r.returncode == 0, msg[-1] if msg else f"rc {r.returncode}", dict(output=msg)
