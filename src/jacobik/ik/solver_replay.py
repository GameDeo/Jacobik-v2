"""GPU fast path: a solver step that is recorded once and replayed (torch.cuda.CUDAGraph). 2026-10-03.

On CUDA an eager gradient step costs about 35 us per tensor operation in launch overhead (Python, autograd
bookkeeping, driver call) and almost nothing in arithmetic; a recorded step replays at about 4 us per kernel.
`ReplaySolver` subclasses `JointIKSolver` and replaces `_solve_impl`; the engine uses it when the device is CUDA
(`solver_class`). GENERATED by dev/tools/jdev/build_replay_solver.py from ik_solver.py (md5 95cfd9131bf0844fb4a2d2150724a3b6): the set-up
before the step loop and the final scoring after it are copied verbatim; the loop between them is rewritten so
that one gradient step is a fixed sequence of GPU operations on fixed memory:
  * all state that survives a step (angles, Adam moments, best snapshot, multipliers, ring buffers, history) lives
    in persistent tensors and is updated in place;
  * the step number is a tensor on the device; Adam's bias corrections come from a table indexed by it; the
    "every W steps" checks run every step under a mask;
  * the eigen-decomposition of the polyhedron fit runs between two recorded halves (it checks its status on the
    host): half A = kinematics, score, 4x4 matrix; half B = everything else incl. the backward pass and the update;
  * no row culling (owner decision 2026-10-03 for this path): every row is optimised for all steps. Culled rows of
    the CPU path keep competing with their best-so-far angles, so this only ever gives a row more steps.
The arithmetic of a step is otherwise the original's, in the original order: run eagerly (CPU, or
`replay = False`) the loop gives bit-identical scores, coordinates and traces to `JointIKSolver` with culling off
(dev/tests/test_solver.py). Step 0 runs eagerly, step 1 is recorded, steps 2.. are replays. If recording
raises, the solve continues eagerly from the device-side step counter and the traceback is kept in LAST["error"].

Switches (environment, read at import):
  JACOBIK_GPU_REPLAY   1 (default): use this solver on CUDA; 0: JointIKSolver on every device.
  JACOBIK_GPU_FAST_FK  1 (default): one-pass kinematics (ik/fk_compose.ComplexFK) in the step; 0: per-ligand loop.
"""
