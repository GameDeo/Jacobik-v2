def _horn_matrix(A: torch.Tensor, B: torch.Tensor) -> torch.Tensor:
    """First half of ik_solver._optimal_rotation_nocentroid: the 4x4 matrix whose top eigenvector is the quaternion."""
    Bsz = B.shape[0]
    H = torch.einsum("bni,bnj->bij", A, B)
    Sxx, Sxy, Sxz = H[:, 0, 0], H[:, 0, 1], H[:, 0, 2]
    Syx, Syy, Syz = H[:, 1, 0], H[:, 1, 1], H[:, 1, 2]
    Szx, Szy, Szz = H[:, 2, 0], H[:, 2, 1], H[:, 2, 2]
    N = H.new_zeros(Bsz, 4, 4)
    N[:, 0, 0] = Sxx + Syy + Szz
    N[:, 0, 1] = Syz - Szy
    N[:, 0, 2] = Szx - Sxz
    N[:, 0, 3] = Sxy - Syx
    N[:, 1, 0] = N[:, 0, 1]
    N[:, 1, 1] = Sxx - Syy - Szz
    N[:, 1, 2] = Sxy + Syx
    N[:, 1, 3] = Szx + Sxz
    N[:, 2, 0] = N[:, 0, 2]
    N[:, 2, 1] = N[:, 1, 2]
    N[:, 2, 2] = -Sxx + Syy - Szz
    N[:, 2, 3] = Syz + Szy
    N[:, 3, 0] = N[:, 0, 3]
    N[:, 3, 1] = N[:, 1, 3]
    N[:, 3, 2] = N[:, 2, 3]
    N[:, 3, 3] = -Sxx - Syy + Szz
    return N


def _horn_rotation(q: torch.Tensor) -> torch.Tensor:
    """Second half: rotation matrix from the quaternion (w, x, y, z)."""
    w, x, y, z = q[:, 0], q[:, 1], q[:, 2], q[:, 3]
    return torch.stack(
        [
            torch.stack([1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)], dim=-1),
            torch.stack([2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)], dim=-1),
            torch.stack([2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)], dim=-1),
        ],
        dim=-2,
    )


class ReplaySolver(JointIKSolver):
    _fixed_shape_replay = True
    replay = True          # record and replay on CUDA (False: the same step functions run eagerly)
    fast_fk = None         # one-pass kinematics in place of the per-ligand loop; None = the module switch FAST_FK
    timing_sync = False    # diagnostics: synchronise after each half so LAST splits half A / eigh / half B

    def _solve_impl(
        self,
        theta_inits: list,
        X_ref: torch.Tensor,
        donor_pos_idxs: list,
        ideal_directions: torch.Tensor,
        debug: bool = False,
        symmetric_groups: Optional[List[List[int]]] = None,
        q3_symmetric_groups: Optional[List[List[int]]] = None,
        row_groups: Optional[torch.Tensor] = None,
        cull_enabled: bool = True,
    ):
        import time as _time0

        _t_enter = _time0.perf_counter()
        # ===== set-up: verbatim from JointIKSolver._solve_impl =====
        device = self.device
        import sys as _sys
        from jacobik.ik.ik_setup import _finalize_solve_state, _init_solve_state

        _cfg_mod = _sys.modules[__name__]
        _st = _init_solve_state(
            self, theta_inits, X_ref, donor_pos_idxs, ideal_directions, symmetric_groups, q3_symmetric_groups, _cfg_mod
        )
        B, B_full, T = _st.B, _st.B_full, _st.T
        X_ref, X_ref_full, cl_d0 = _st.X_ref, _st.X_ref_full, _st.cl_d0
        donor_pos_idxs, ideal_directions_dev, thetas = _st.donor_pos_idxs, _st.ideal_directions_dev, _st.thetas
        has_closure, _cl_a, _cl_b, _cl_d0 = _st.has_closure, _st._cl_a, _st._cl_b, _st._cl_d0
        handoff_delta, adam_m, adam_v = _st.handoff_delta, _st.adam_m, _st.adam_v
        endpoint_m, endpoint_v, endpoint_t = _st.endpoint_m, _st.endpoint_v, _st.endpoint_t
        best_score_ever, best_score_thetas = _st.best_score_ever, _st.best_score_thetas
        W, score_ring, ever_plateaued = _st.W, _st.score_ring, _st.ever_plateaued
        MW, violation_ring, mu_shape_frozen = _st.MW, _st.violation_ring, _st.mu_shape_frozen
        SW, sym_violation_ring, sym_angle_violation_ring = _st.SW, _st.sym_violation_ring, _st.sym_angle_violation_ring
        mu_sym_frozen, mu_sym_angle_frozen = _st.mu_sym_frozen, _st.mu_sym_angle_frozen
        mu_shape, mu_sym, mu_sym_angle = _st.mu_shape, _st.mu_sym, _st.mu_sym_angle
        q3_site_to_idx, q3_mode_override = _st.q3_site_to_idx, _st.q3_mode_override
        _sym_group_idx_tensors, _n_sym_groups, _sym_w = _st._sym_group_idx_tensors, _st._n_sym_groups, _st._sym_w
        _q3_sym_group_idx_tensors, _q3_sym_haptic = _st._q3_sym_group_idx_tensors, _st._q3_sym_haptic
        _n_q3_sym_groups, _q3_sym_w = _st._n_q3_sym_groups, _st._q3_sym_w
        _step_scale_tabs, phase = _st._step_scale_tabs, _st.phase


        # ===== replay-friendly step loop =====
        groups_c = row_groups.to(device) if row_groups is not None else None
        dt = thetas[0].dtype
        tl = torch.zeros(1, dtype=torch.long, device=device)                      # step index, on the device
        bc1 = torch.tensor([1.0 - _ADAM_BETA1 ** (i + 1) for i in range(T)], dtype=dt, device=device)
        bc2 = torch.tensor([1.0 - _ADAM_BETA2 ** (i + 1) for i in range(T)], dtype=dt, device=device)
        nan = float("nan")
        hist_res = torch.full((T, B), nan, device=device, dtype=dt)
        hist_score = torch.full((T, B), nan, device=device, dtype=dt)
        hist_gn = torch.full((T, B), nan, device=device, dtype=dt)
        hist_shape = torch.full((T, B), nan, device=device, dtype=dt)
        q_static = torch.zeros(B, 4, device=device, dtype=dt)
        S: Dict[str, torch.Tensor] = {}
        cfk = None
        if FAST_FK if self.fast_fk is None else self.fast_fk:
            from jacobik.ik.fk_compose import ComplexFK

            cfk = ComplexFK(self.fks)
            if not cfk.supported:
                cfk = None

        def part_a():
            if cfk is not None:
                X_current = cfk.apply(thetas, X_ref)
            else:
                X_current = _ref_rows(X_ref, B)
                for fk_li, theta_li in zip(self.fks, thetas):
                    X_current = fk_li.apply(theta_li, X_current)
            all_donor_pos_grad = self.ge.donor_positions(X_current)
            stat_score, _comps = self.scorer.score(
                X_current, q3_mode_override=q3_mode_override, donor_pos=all_donor_pos_grad, row_groups=groups_c,
            )
            stat_score = stat_score + self._bend_prior(thetas)
            donor_unit_vecs = F.normalize(all_donor_pos_grad, dim=-1)
            with torch.no_grad():
                N = _horn_matrix(ideal_directions_dev, donor_unit_vecs.detach())
            S.update(X=X_current, donor=all_donor_pos_grad, stat=stat_score, unit=donor_unit_vecs, N=N)

        def mid():
            with torch.no_grad():
                _, evecs = torch.linalg.eigh(S["N"])
                q_static.copy_(evecs[:, :, -1])

        def part_b():
            X_current, all_donor_pos_grad, stat_score, donor_unit_vecs = S["X"], S["donor"], S["stat"], S["unit"]
            all_donor_pos_det = all_donor_pos_grad.detach()
            sym_penalty = X_ref.new_zeros(B)
            sym_angle_penalty = X_ref.new_zeros(B)
            with torch.no_grad():
                R_opt = _horn_rotation(q_static)
            aligned_ideal = torch.einsum("bij,bnj->bni", R_opt, ideal_directions_dev)
            per_donor_sq = ((aligned_ideal - donor_unit_vecs) ** 2).sum(-1)
            n_sh = per_donor_sq.shape[-1]
            if n_sh > 1:
                tau = _LSE_TEMP
                shape_dev = (torch.logsumexp(tau * per_donor_sq, dim=-1) - math.log(n_sh)) / tau
            else:
                shape_dev = per_donor_sq.mean(dim=-1)
            violation = (shape_dev - self.shape_tol).clamp(min=0.0)
            constraint_loss = mu_shape.detach() * violation + 0.5 * _SHAPE_RHO * violation**2

            if symmetric_groups:
                all_donor_norms = all_donor_pos_grad.norm(dim=-1)
                for _gi, idx_t in enumerate(_sym_group_idx_tensors):
                    d_g = all_donor_norms[:, idx_t]
                    dev_g = d_g - d_g.mean(dim=-1, keepdim=True)
                    if _sym_w is None:
                        sym_penalty = sym_penalty + (dev_g**2).mean(dim=-1)
                    else:
                        sym_penalty = sym_penalty + _sym_w[_gi] * (dev_g**2).mean(dim=-1)
                if _n_sym_groups > 0 and _sym_w is None:
                    sym_penalty = sym_penalty / _n_sym_groups
                if q3_site_to_idx:
                    if _q3_sym_group_idx_tensors:
                        q3_angles_now = self.ge.q3_approach_angles(X_current, haptic=_q3_sym_haptic)
                        for _gi, idx_t2 in enumerate(_q3_sym_group_idx_tensors):
                            a_g = q3_angles_now[:, idx_t2]
                            dev_a = a_g - a_g.mean(dim=-1, keepdim=True)
                            if _q3_sym_w is None:
                                sym_angle_penalty = sym_angle_penalty + (dev_a**2).mean(dim=-1)
                            else:
                                sym_angle_penalty = sym_angle_penalty + _q3_sym_w[_gi] * (dev_a**2).mean(dim=-1)
                        if _q3_sym_w is None:
                            sym_angle_penalty = sym_angle_penalty / _n_q3_sym_groups

            sym_violation = (sym_penalty - _SYM_TOL).clamp(min=0.0)
            sym_angle_violation = (sym_angle_penalty - _SYM_TOL).clamp(min=0.0)
            if phase is not None:
                phase.observe(tl, -stat_score.detach() + constraint_loss.detach()
                              + mu_sym.detach() * sym_violation.detach() + .5 * _SYM_RHO * sym_violation.detach()**2
                              + mu_sym_angle.detach() * sym_angle_violation.detach() + .5 * _SYM_RHO * sym_angle_violation.detach()**2)
                constraint_loss = phase.aid('shape', constraint_loss)
                sym_violation = phase.aid('symmetry', sym_violation)
                sym_angle_violation = phase.aid('symmetry', sym_angle_violation)

            constraint_loss = (
                constraint_loss
                + mu_sym.detach() * sym_violation
                + 0.5 * _SYM_RHO * sym_violation**2
                + mu_sym_angle.detach() * sym_angle_violation
                + 0.5 * _SYM_RHO * sym_angle_violation**2
            )

            snap_score = stat_score.detach()
            if has_closure:
                clos = (((X_current[:, _cl_a] - X_current[:, _cl_b]).norm(dim=-1) - _cl_d0) ** 2).sum(dim=-1)
                snap_score = snap_score - 1000.0 * clos.detach()

            with torch.no_grad():
                # plateau check: ring written every step, flag only taken on the last slot of a window
                slot = tl % W
                score_ring.index_copy_(0, slot, stat_score.detach().unsqueeze(0))
                score_range = score_ring.max(dim=0).values - score_ring.min(dim=0).values
                ever_plateaued.logical_or_((score_range < _PLATEAU_ATOL) & (slot == W - 1))
                # best-score snapshot
                improved = snap_score > best_score_ever
                best_score_ever.copy_(torch.where(improved, snap_score, best_score_ever))
                sel = improved.view(-1, *([1] * (thetas[0].dim() - 1)))
                for li, theta_li in enumerate(thetas):
                    best_score_thetas[li].copy_(
                        torch.where(sel.expand_as(theta_li), theta_li.detach(), best_score_thetas[li]))

            score_grads = None
            if phase is not None:
                score_grads = torch.autograd.grad(-stat_score.sum(), thetas, retain_graph=True, create_graph=phase.sigma_source == 'curvature', allow_unused=True)
                score_grads = [g if g is not None else torch.zeros_like(th) for g, th in zip(score_grads, thetas)]
                if phase.sigma_source == 'curvature':
                    phase.curvature(score_grads, thetas, float(self.scorer._agg_norm()))
            combined_loss = (-stat_score + constraint_loss).sum()
            grads_all = torch.autograd.grad(combined_loss, thetas, allow_unused=True)

            total_grads: List[torch.Tensor] = []
            for li, (didx, theta_li) in enumerate(zip(donor_pos_idxs, thetas)):
                g = grads_all[li] if grads_all[li] is not None else torch.zeros_like(theta_li)
                n_d_i = didx.shape[0]
                if n_d_i == 2:
                    with torch.no_grad():
                        d_pos = all_donor_pos_det[:, didx, :]
                        null_vec = d_pos[:, 0, :] - d_pos[:, 1, :]
                        null_norm = null_vec.norm(dim=-1, keepdim=True).clamp(min=1e-8)
                        n_hat = null_vec / null_norm
                        I3 = torch.eye(3, dtype=n_hat.dtype, device=n_hat.device).unsqueeze(0).expand(B, -1, -1)
                        P_keep = I3 - torch.bmm(n_hat.unsqueeze(-1), n_hat.unsqueeze(-2))
                    omega_proj = torch.bmm(P_keep, g[:, 3:6].unsqueeze(-1)).squeeze(-1)
                    g = g.clone()
                    g[:, 3:6] = (torch.where(phase.active[:, None], g[:, 3:6], omega_proj)
                                   if phase is not None and ('projection' in phase.release or phase.whole) else omega_proj)
                total_grads.append(g)

            r = -stat_score + constraint_loss

            with torch.no_grad():
                grad_norm_b = torch.cat([g.reshape(B, -1) for g in total_grads], dim=-1).norm(dim=-1)
                hist_res.index_copy_(0, tl, r.detach().unsqueeze(0))
                hist_score.index_copy_(0, tl, stat_score.detach().unsqueeze(0))
                hist_gn.index_copy_(0, tl, grad_norm_b.unsqueeze(0))
                hist_shape.index_copy_(0, tl, shape_dev.detach().unsqueeze(0))

                mslot = tl % MW
                violation_ring.index_copy_(0, mslot, violation.detach().unsqueeze(0))
                v_range = violation_ring.max(dim=0).values - violation_ring.min(dim=0).values
                mu_shape_frozen.logical_or_((v_range < _MU_SHAPE_STALL_ATOL) & (mslot == MW - 1))
                mu_increment = _SHAPE_RHO * violation.detach()
                mu_increment = torch.where(mu_shape_frozen, torch.zeros_like(mu_increment), mu_increment)
                mu_shape.copy_((mu_shape + mu_increment).clamp(min=0.0))

                sslot = tl % SW
                sym_violation_ring.index_copy_(0, sslot, sym_violation.detach().unsqueeze(0))
                sym_angle_violation_ring.index_copy_(0, sslot, sym_angle_violation.detach().unsqueeze(0))
                sym_v_range = sym_violation_ring.max(dim=0).values - sym_violation_ring.min(dim=0).values
                sym_angle_v_range = (sym_angle_violation_ring.max(dim=0).values
                                     - sym_angle_violation_ring.min(dim=0).values)
                last = sslot == SW - 1
                mu_sym_frozen.logical_or_((sym_v_range < _SYM_STALL_ATOL) & last)
                mu_sym_angle_frozen.logical_or_((sym_angle_v_range < _SYM_STALL_ATOL) & last)
                mu_sym_increment = _SYM_RHO * sym_violation.detach()
                mu_sym_angle_increment = _SYM_RHO * sym_angle_violation.detach()
                mu_sym_increment = torch.where(mu_sym_frozen, torch.zeros_like(mu_sym_increment), mu_sym_increment)
                mu_sym_angle_increment = torch.where(
                    mu_sym_angle_frozen, torch.zeros_like(mu_sym_angle_increment), mu_sym_angle_increment)
                mu_sym.copy_((mu_sym + mu_sym_increment).clamp(min=0.0))
                mu_sym_angle.copy_((mu_sym_angle + mu_sym_angle_increment).clamp(min=0.0))

            b1, b2, eps_a = _ADAM_BETA1, _ADAM_BETA2, _ADAM_EPS
            with torch.no_grad():
                c1 = bc1.index_select(0, tl)
                c2 = bc2.index_select(0, tl)
                lr_t = self.lr
                if phase is not None:
                    scales = ([tab.index_select(0, tl) for tab in _step_scale_tabs]
                              if _step_scale_tabs is not None else None)
                    steps = phase.update(tl, total_grads, [g * float(self.scorer._agg_norm()) for g in score_grads],
                                         (-stat_score + constraint_loss).detach(), scales, self.lr)
                else:
                    steps = []
                    for li, (theta_li, g) in enumerate(zip(thetas, total_grads)):
                        adam_m[li].copy_(b1 * adam_m[li] + (1.0 - b1) * g)
                        adam_v[li].copy_(b2 * adam_v[li] + (1.0 - b2) * g**2)
                        if endpoint_m is not None:
                            endpoint_m[li].copy_(adam_m[li]); endpoint_v[li].copy_(adam_v[li])
                            endpoint_t.copy_((tl+1).expand_as(endpoint_t))
                        m_hat = adam_m[li] / c1
                        v_hat = adam_v[li] / c2
                        step = lr_t * m_hat / (v_hat.sqrt() + eps_a)
                        if handoff_delta is not None:
                            handoff_delta[li].copy_(step.abs())
                        if _step_scale_tabs is not None and _step_scale_tabs[li] is not None:
                            step = step * _step_scale_tabs[li].index_select(0, tl)
                        steps.append(step)
                for li, (theta_li, step) in enumerate(zip(thetas, steps)):
                    if li in cl_d0:
                        c0_ = self.fks[li]._macro_col0
                        c1_ = c0_ + self.fks[li].n_macro_joints
                        step = step.clone()
                        step[:, c0_:c1_] = self.fks[li].closure_fused_step(X_current, cl_d0[li], step[:, c0_:c1_])
                    if phase is not None:
                        step = torch.where(phase.done[:, None], 0., step)
                    theta_li.data -= step
                    if theta_li.shape[1] > 6:
                        theta_li.data[:, 6:] = wrap_angle(theta_li.data[:, 6:])
                    theta_li.data[:, 3:6] = _renorm_axisangle(theta_li.data[:, 3:6])
                tl.add_(1)

        import time as _time

        def _now():
            if device.type == "cuda":
                torch.cuda.synchronize()
            return _time.perf_counter()

        LAST.clear()
        LAST.update(mode="eager", replayed=0, B=B, T=T, fast_fk=cfk is not None, error=None,
                    s_setup=_now() - _t_enter, s_step0=0.0, s_record=0.0, s_replay=0.0, s_eigh=0.0, s_eager=0.0, s_final=0.0)
        t = 0
        if self.replay and device.type == "cuda" and JointIKSolver.trace_hook is None and T > 2:
            try:
                _t0 = _now()
                part_a(); mid(); part_b()                     # step 0 eagerly: also the warm-up
                t = 1
                _t1 = _now()
                LAST["s_step0"] = _t1 - _t0
                # The leaf angles' gradient-accumulation nodes remember the stream of the eager step 0; let the
                # autograd engine redirect them to the recording stream (PyTorch's own suggested remedy).
                _ovr = getattr(torch.autograd.graph, "set_override_stale_capture_stream", None)
                if _ovr is not None:
                    _ovr(True)
                g_a, g_b = torch.cuda.CUDAGraph(), torch.cuda.CUDAGraph()
                with torch.cuda.graph(g_a):
                    part_a()
                g_a.replay()                                   # recording does not execute: run half A for step 1
                mid()
                with torch.cuda.graph(g_b):
                    part_b()
                g_b.replay()
                t = 2
                LAST["mode"] = "replay"
                _t2 = _now()
                LAST["s_record"] = _t2 - _t1
                _te = _ta = _tb = 0.0
                _ts = self.timing_sync
                while t < T:
                    _a0 = _time.perf_counter()
                    g_a.replay()
                    if _ts:
                        torch.cuda.synchronize()
                    _e0 = _time.perf_counter()
                    mid()
                    if _ts:
                        torch.cuda.synchronize()
                    _b0 = _time.perf_counter()
                    g_b.replay()
                    if _ts:
                        torch.cuda.synchronize()
                    _b1 = _time.perf_counter()
                    _ta += _e0 - _a0
                    _te += _b0 - _e0
                    _tb += _b1 - _b0
                    t += 1
                    LAST["replayed"] += 1
                    if phase is not None and t % 8 == 0 and bool(phase.stop.item()):
                        break
                LAST["s_replay"] = _now() - _t2
                LAST["s_eigh"] = _te
                LAST["s_half_a"] = _ta
                LAST["s_half_b"] = _tb
            except Exception:
                LAST["error"] = traceback.format_exc()[-3000:]
                LAST["mode"] = "eager after failed recording at step %d" % t
                log.warning("step recording failed at step %d; continuing eagerly\n%s", t, LAST["error"])
                t = int(tl.item())                             # steps actually applied
            finally:
                _ovr = getattr(torch.autograd.graph, "set_override_stale_capture_stream", None)
                if _ovr is not None:
                    _ovr(False)
        _t3 = _now()
        while t < T and not (phase is not None and t % 8 == 0 and bool(phase.stop.item())):
            part_a(); mid(); part_b()
            t += 1
            if phase is not None and t % 8 == 0 and bool(phase.stop.item()):
                break
        LAST["steps_executed"] = t
        _t4 = _now()
        LAST["s_eager"] = _t4 - _t3

        # ===== final scoring: verbatim from JointIKSolver._solve_impl =====
        best_thetas = best_score_thetas  # list of (B, 6+Ji)
        best_thetas, converged, final_score = _finalize_solve_state(
            self,
            best_thetas,
            X_ref_full,
            B,
            row_groups,
            q3_mode_override,
            endpoint_m,
            endpoint_v,
            endpoint_t,
            T,
            handoff_delta,
            ever_plateaued,
            _cfg_mod,
        )


        LAST["s_final"] = _now() - _t4
        solve_trace = {
            "residual": hist_res.cpu().numpy(),
            "score": hist_score.cpu().numpy(),
            "grad_norm": hist_gn.cpu().numpy(),
            "shape_dev": hist_shape.cpu().numpy(),
        }
        thetas_final = [th.detach() for th in best_thetas]
        return thetas_final, converged, final_score, solve_trace


def solver_class(device):
    """The solver class the engine should use on `device`: ReplaySolver on CUDA (when enabled), else JointIKSolver."""
    dev = torch.device(device)
    # Whole-run sanity arms skip the production Adam loop entirely.
    if IKM.OPTIMIZER in _IRPROP:
        return JointIKSolver
    if ENABLED and (dev.type == "cuda" or FORCE_ON_CPU):
        return ReplaySolver
    return JointIKSolver
