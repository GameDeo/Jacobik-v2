def build(kind: str, out: Path, qos: str, minutes: int, with_p: bool, prod_sha: str, df_db="$DF_DB", damaged_dir="$DAMAGED_DIR") -> Path:
    ph = phases(kind, with_p, df_db, damaged_dir)
    arms = "\n".join(f"cat > \"$OUT/arms/{n}.json\" <<'EOF'\n{json.dumps(a)}\nEOF" for n, _, a, _ in ph)
    def line(n, c, db, pin):
        text = PHASE.replace("@N@", n).replace("@CODES@", ",".join(c)).replace("@SEEDS@", ",".join(map(str, SEEDS))).replace("@DB@", db)
        # a one-parent phase gains nothing from four runners (three would only start up and find the queue empty): pin it to one GPU
        return text if pin is None else f'  if [ "$g" = {pin} ]; then\n{text}\n  fi'
    pinned = {n: i % 4 for i, n in enumerate(n for n, c, _, _ in ph if len(c) == 1)}
    lines = "\n".join(line(n, c, db, pinned.get(n)) for n, c, _, db in ph)
    extra = "; DAMAGED_DIR (the four damaged-trial DBs and sidecars)" if kind == "step6" else ""
    text = (SCRIPT.replace("@QOS@", qos).replace("@MINUTES@", str(minutes)).replace("@KIND@", kind).replace("@JOB@", f"jk-ds-{kind}")
            .replace("@PROD_SHA@", prod_sha).replace("@EXTRA_ENV@", extra).replace("@ARMS@", arms).replace("@PHASES@", lines))
    out.mkdir(parents=True, exist_ok=True)
    path = out / f"ds_{kind}.sbatch"
    path.write_text(text)
    (out / f"ds_{kind}_plan.json").write_text(json.dumps(dict(kind=kind, qos=qos, minutes=minutes, with_p=with_p, seeds=SEEDS,
                                                             phases=[dict(name=n, codes=c, arms=a, db=db) for n, c, a, db in ph]), indent=1))
    return path


# ----------------------------------------------------------------------------------------------- assemble (after the job)
STAGE_PHASES = {"stage1": ("g1_C", "g1_D"), "stage2": ("g2_C", "g2_D")}


def arm_identity(df_sha: str, prod_sha: str) -> dict:
    flags = {"C": {}, "S": P_FLAGS, "D": DF_FLAGS, "DS": {**DF_FLAGS, **P_FLAGS}}
    db = {"C": prod_sha, "S": prod_sha, "D": df_sha, "DS": df_sha}
    return {a: dict(flags=flags[a], db_sha256=db[a]) for a in flags}


def _enrich(args):
    path, = args
    from tools.jgen.d3.worker import enrich_record
    try:
        enrich_record(Path(path))
        return path, None
    except Exception as exc:  # noqa: BLE001 - recorded as a failed record, exactly as the D3 worker does
        r = json.loads(Path(path).read_text())
        r.update(status="failed", reason="enrichment: " + repr(exc))
        Path(path).write_text(json.dumps(r))
        return path, repr(exc)


def assemble(runs: Path, dest: Path, stage: str, pm_prefix: str, df_sha: str, prod_sha: str, workers: int = 3) -> dict:
    """runs = the fetched job directory (phase/g<i>/<arm>/{records,xyz}); dest = the stage root for ``tools.jgen.d3.analyse``.
    A record whose flags or DB differ from its registered arm stops the assembly (an ok or a failed record alike)."""
    from concurrent.futures import ProcessPoolExecutor
    ident = arm_identity(df_sha, prod_sha)
    todo, n_records = [], 0
    for name in STAGE_PHASES[stage]:
        for gdir in sorted((runs / name).glob("g[0-3]")):
            for arm_dir in sorted(p for p in gdir.iterdir() if (p / "records").is_dir()):
                arm = arm_dir.name
                (dest / arm / "records").mkdir(parents=True, exist_ok=True)
                xyz = dest / arm / "xyz"; xyz.mkdir(parents=True, exist_ok=True)
                for code_dir in (arm_dir / "xyz").glob("*") if (arm_dir / "xyz").is_dir() else []:
                    link = xyz / code_dir.name
                    if not link.exists():
                        link.symlink_to(code_dir.resolve(), target_is_directory=True)
                for rec in sorted((arm_dir / "records").glob("*.json")):
                    r = json.loads(rec.read_text())
                    if arm in ident and "flags" in r and (r["flags"] != ident[arm]["flags"] or r.get("constraints_db_sha256") not in (None, ident[arm]["db_sha256"])):
                        raise ValueError(f"{rec}: flags/DB differ from arm {arm}")
                    if r.get("pool_manifest"):
                        r["pool_manifest"] = r["pool_manifest"].replace(f"{pm_prefix}/{name}/{gdir.name}/{arm}", str(arm_dir.resolve()), 1)
                    tgt = dest / arm / "records" / rec.name
                    if tgt.exists():
                        raise FileExistsError(f"{tgt}: two phases wrote the same record")
                    tgt.write_text(json.dumps(r)); n_records += 1
                    if r.get("status") == "ok":
                        todo.append((str(tgt),))
    errors = []
    with ProcessPoolExecutor(max_workers=workers) as ex:
        for path, err in ex.map(_enrich, todo, chunksize=8):
            if err:
                errors.append([path, err])
    summary = dict(stage=stage, records=n_records, enriched=len(todo) - len(errors), enrichment_errors=errors)
    (dest / "assemble.json").write_text(json.dumps(summary, indent=1))
    return summary


ELIGIBILITY = Path(__file__).resolve().parents[4] / "campaigns/ds/gate_eligibility_v1.json"


def write_manifest(dest: Path, stage: str, df_sha: str, prod_sha: str, curvature: Path | None, arms: list,
                   strata: str = "all", link_from: Path | None = None) -> dict:
    """strata ``all``: every parent of the stage (ambiguous and unrepaired targets stay visible and count as missing/failed when they fail).
    ``primary``: the frozen source-based eligibility (valid + repaired strata, ``in_corrected_primary``); the arm record directories are
    symlinked from ``link_from`` (the ``all`` root) so both analyses read the same records. ``analyse`` writes ``analysis.json`` once per root."""
    from tools.jgen.d3 import panels
    codes = list(panels.stage1() if stage == "stage1" else panels.stage2())
    if strata == "primary":
        elig = json.loads(ELIGIBILITY.read_text())["parents"]
        n = int(stage[-1])
        keep = {p["code"] for p in elig if p["stage"] == n and p["in_corrected_primary"]}
        codes = [c for c in codes if c in keep]
        if link_from is not None:
            dest.mkdir(parents=True, exist_ok=True)
            for a in arms:
                if not (dest / a).exists():
                    (dest / a).symlink_to((link_from / a).resolve(), target_is_directory=True)
    m = dict(stage=stage, label="DSG", strata=strata, codes=codes, seeds=SEEDS, arms=arms, identities={a: arm_identity(df_sha, prod_sha)[a] for a in arms})
    if curvature:
        m["curvature"] = {a: json.loads((curvature / a / "summary.json").read_text()) for a in ("C", "D", "DS", "S") if (curvature / a / "summary.json").exists()}
    (dest / "manifest.json").write_text(json.dumps(m, indent=1))
    return m


