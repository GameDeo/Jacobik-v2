def phases(kind: str, with_p: bool, df_db: str, damaged_dir: str):
    """[(name, codes, arms, db)]"""
    C = dict(arm="C", flags={})
    D = dict(arm="D", flags=DF_FLAGS)
    DS = dict(arm="DS", flags={**DF_FLAGS, **P_FLAGS})
    if kind == "step6":
        out = [("s6_C", DEV, [C], PROD_DB), ("s6_DF", DEV, [D, DS], df_db)]
        for name, code in DAMAGED.items():
            out.append((f"s6_{name}", [code], [D, DS], f"{damaged_dir}/{name}.json"))
        return out
    from tools.jgen.d3 import panels
    s1, s2 = list(panels.stage1()), list(panels.stage2())
    out = [("g1_C", s1, [C] + ([dict(arm="S", flags=P_FLAGS)] if with_p else []), PROD_DB),
           ("g1_D", s1, [D] + ([DS] if with_p else []), df_db), ("g2_C", s2, [C], PROD_DB), ("g2_D", s2, [D], df_db)]
    return out


