    p.add_argument("--runs", type=Path, help="assemble: the fetched job directory"); p.add_argument("--pm-prefix", help="assemble: the job's $OUT on Perlmutter")
    p.add_argument("--df-sha", help="assemble/manifest: sha256 of the candidate DB"); p.add_argument("--curvature", type=Path)
    p.add_argument("--arms", default="C,D", help="manifest: comma list of arms present")
    p.add_argument("--strata", choices=["all", "primary"], default="all", help="manifest: all parents of the stage, or the frozen primary eligibility")
    p.add_argument("--link-from", type=Path, help="manifest --strata primary: the `all` stage root whose arm directories are linked")
    p.add_argument("--with-p", action="store_true", help="gate: also run S (production + P) and DS (corrected + P)")
    p.add_argument("--prod-sha", default="d87b81a5d6297e0251a881b871f477678ede79fc2bce694b72c4dba1c5fe10c4")
